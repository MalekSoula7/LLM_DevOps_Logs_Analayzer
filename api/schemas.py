"""Pydantic v2 request/response schemas for the DevOps Log Analyzer API."""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field


class ClassifyRequest(BaseModel):
    """Request body for POST /classify."""

    log_text: str = Field(
        ...,
        min_length=10,
        description=(
            "Raw multi-line CI/CD pipeline log snippet to classify. "
            "Must be at least 10 characters. Truncated at 4000 chars server-side."
        ),
        examples=["npm ERR! code ENOENT\nnpm ERR! path /app/package.json\nBuild failed with exit code 1"],
    )


class ClassifyResponse(BaseModel):
    """Response body for POST /classify."""

    predicted_label: str = Field(
        ...,
        description="Predicted failure category. One of: build_failure, test_failure, timeout, config_error, infra_failure.",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Model confidence score for the predicted label (0–1).",
    )
    explanation: str = Field(
        ...,
        description="2-sentence DevOps expert explanation of the failure, generated by Mistral-7B via HuggingFace.",
    )
    model_version: str = Field(
        ...,
        description="Identifier of the model used for this prediction (MLflow run ID or 'local').",
    )
    inference_time_ms: float = Field(
        ...,
        description="End-to-end inference latency in milliseconds, including embedding, prediction, and explanation.",
    )


class HealthResponse(BaseModel):
    """Response body for GET /health."""

    status: str = Field(..., description="Always 'ok' when the API is running.")
    model_loaded: bool = Field(..., description="True if a classifier model is loaded and ready.")
    mlflow_connected: bool = Field(..., description="True if the MLflow tracking server is reachable.")


class DriftReportResponse(BaseModel):
    """Response body for GET /drift-report."""

    drift_detected: bool = Field(..., description="True if data drift was detected in the last run.")
    drift_share: float = Field(..., description="Share of features (0–1) that showed statistically significant drift.")
    drifted_features: int = Field(..., description="Number of embedding dimensions that drifted.")
    total_features: int = Field(..., description="Total number of embedding dimensions evaluated.")
    timestamp: str = Field(..., description="ISO 8601 timestamp of the drift detection run.")
    html_report: str = Field(..., description="Filesystem path to the Evidently HTML report.")


class PipelineRunSummary(BaseModel):
    """A single inference run record for GET /pipeline-status."""

    timestamp: str = Field(..., description="ISO 8601 timestamp of the inference run.")
    log_count: int = Field(..., description="Number of logs processed in this run.")
    drift_detected: bool = Field(..., description="Whether drift was detected during this run.")
    output_file: str = Field(..., description="Filename of the saved inference results JSON.")
    avg_confidence: float = Field(..., description="Mean confidence score across all classified logs in this run.")


class PipelineStatusResponse(BaseModel):
    """Response body for GET /pipeline-status."""

    runs: list[PipelineRunSummary] = Field(
        ...,
        description="Last up to 10 inference runs, newest first.",
    )
    total_logs_processed: int = Field(
        ...,
        description="Total number of logs processed across all returned runs.",
    )


class MetricsResponse(BaseModel):
    """Response body for GET /metrics."""

    best_model: str = Field(..., description="Algorithm name of the best-performing classifier.")
    weighted_f1: float = Field(..., description="Weighted F1 score of the model on the held-out test set.")
    per_class: dict[str, dict[str, float]] = Field(
        ...,
        description="Per-class precision, recall, and F1 scores keyed by label name.",
    )
    n_train: int = Field(..., description="Number of training samples used.")
    n_test: int = Field(..., description="Number of test samples used.")
    timestamp: str = Field(..., description="ISO 8601 timestamp of the last training run.")
    run_id: str | None = Field(None, description="MLflow run ID associated with this model.")


class SimulateDriftResponse(BaseModel):
    """Response body for POST /simulate-drift."""

    message: str = Field(..., description="Human-readable summary of the drift simulation.")
    drift_detected: bool = Field(..., description="True if drift was detected in the drift dataset.")
    drift_share: float = Field(..., description="Share of features that drifted.")
    inference_summary: dict[str, Any] = Field(
        ...,
        description="Summary of the inference run on the drift dataset.",
    )
